/** Whether one relay took a test response signed by each key: null when it did, else why not. */
export interface RelayTakes {
  url: string;
  watch: string | null;
  executor: string | null;
}

/**
 * Publishes one test response signed by each key to every relay, and says which relays took which.
 *
 * **A relay that takes the watch key and refuses the executor's is the quiet failure here.** The
 * executor's key is new and has no history, so a relay that limits new keys -- an allowlist, payment,
 * proof of work, web of trust, a rate limit on new keys -- takes the watch key's copies and refuses the
 * executor's own. A phone given the executor key then hears only copies from it, and no `Distress`
 * ends there, while the box looks healthy (`escalation.spec.md`, *Every relay the box uses must take
 * both keys*). The other way round is as bad for every phone not handed the executor key, which hears
 * only the copy.
 *
 * **Sent as the executor sends** [review: box safety]: its own first, then the watch key's copy naming
 * it, both handed to the pool before either is awaited. A relay that refuses the second event of a pair
 * -- a rate limit -- refuses here exactly what it refuses in production, so the check blames the key a
 * Distress would lose rather than the other one.
 *
 * The test is the kind the executor sends: an ephemeral `20912`, addressed to and sealed for the key
 * that signed it, so it is stored nowhere and nobody else can read it.
 */
export async function relaysTakeBoth(pool: SimplePool, urls: readonly string[], watch: Keypair, executor: Keypair): Promise<RelayTakes[]> {
  const unique = [...new Set(urls)];
  const payload: ResponsePayload = {
    type: "escalation-status",
    responder: { kind: "node", callsign: "escalation" },
    text: "Relay check from navcom-escalation --check. Not an emergency.",
    provenance: null,
  };
  const test = (key: Keypair, body: ResponsePayload) =>
    finalizeEvent(
      {
        kind: KIND_RESPONSE,
        created_at: Math.floor(Date.now() / 1000),
        tags: [["p", key.pubkey]],
        content: sealResponse(key.secretKey, key.pubkey, body),
      },
      key.secretKey,
    );
  const own = test(executor, payload);
  const copy = test(watch, watchCopy(payload, own.id));
  const sentOwn = pool.publish(unique, own);
  const sentCopy = pool.publish(unique, copy);
  const [e, w] = await Promise.all([Promise.allSettled(sentOwn), Promise.allSettled(sentCopy)]);
  const why = (r: PromiseSettledResult<string> | undefined) =>
    !r ? "no answer" : r.status === "fulfilled" ? null : String(r.reason instanceof Error ? r.reason.message : r.reason);
  return unique.map((url, i) => ({ url, watch: why(w[i]), executor: why(e[i]) }));
}
